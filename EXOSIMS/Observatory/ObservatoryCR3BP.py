import astropy.units as u
import hashlib
import os
import numpy as np
import warnings
from scipy.interpolate import interp1d
from importlib.metadata import version
from pathlib import Path
from orbit_gen import Family, Orbit, RunConfig
from orbit_gen.setup.config import ContinuationConfig
from orbit_gen.setup.system_config import EM_SYSTEM, SE_SYSTEM
from orbit_gen.setup.presets import PRESETS
from orbit_gen.utils import units

from EXOSIMS.Prototypes.Observatory import Observatory

_SYSTEMS = {"EM": EM_SYSTEM, "SE": SE_SYSTEM}


class ObservatoryCR3BP(Observatory):
    """Observatory on a CR3BP periodic orbit, generated via ``orbit-gen``.

    The ``orbit`` method from the Observatory prototype is overloaded to
    implement a space telescope on a periodic orbit (e.g. halo, Lyapunov)
    generated by ``orbit-gen``.

    Args:
        system (str):
            CR3BP system used, ``"SE"`` for Sun-Earth, ``"EM"`` for
            Earth-Moon. Defaults to ``"SE"``.
        preset (str):
            Key of :py:data:`orbit_gen.setup.presets.PRESETS` naming the orbit
            used as the initial condition for continuation. The initial
            condition is ``PRESETS[preset][system]``, so the preset must be
            available for ``system``. Defaults to ``"L2_Northern_Halo"``.
        desired_period (float, optional):
            Desired orbital period in days. Used to determine which generated
            orbit is used for the observatory. A value of None will cause the
            last orbit generated to be selected. Defaults to None.
        eps (float):
            Convergence tolerance on the constraint residual norm.
            Defaults to 1e-10.
        max_iter (int):
            Maximum number of Newton iterations for a single differential
            correction attempt. Defaults to 100.
        max_period_days (float):
            Maximum allowable full orbit period, in days. Defaults to infinity
            (no limit).
        max_solutions (int):
            Maximum number of continuation steps before terminating
            continuation. Each step adds at most one orbit to the family.
            Defaults to 20.
        step (float):
            Pseudo-arclength continuation step size in canonical units.
            Defaults to 0.01.
        **specs:
            :ref:`sec:inputspec`

    Attributes:
        canonical_units (orbit_gen.setup.system_config.CanonicalUnits):
            Canonical length/time scales for the orbit's system.
        orbit_period_days (astropy.units.Quantity):
            Orbit period in days.
        observatory_orbit (orbit_gen.orbit.Orbit):
            The single orbit (from ``family.orbits[orbit_index]``) this
            Observatory sits on.
        primary_name (str):
            Name of the primary body in the CR3BP.
        r_interp (scipy.interpolate.interp1d):
            Interpolant for synodic-frame position, evaluated at canonical
            time, returning canonical-unit position.
        secondary_name (str):
            Name of the secondary body in the CR3BP.
        v_interp (scipy.interpolate.interp1d):
            Interpolant for synodic-frame velocity, same units convention
            as r_interp. Optional -- only needed if velocity is used
            downstream (e.g. dV calculations).

    .. note::

        All CR3BP-frame quantities (position, velocity, time) are stored and
        interpolated in canonical units. Conversion to physical units (AU,
        days) happens only at the boundary, inside ``orbit()``.

    """

    def __init__(
        self,
        system="SE",
        preset="L2_Northern_Halo",
        desired_period=None,
        eps=1e-10,
        max_iter=100,
        max_period_days=float("inf"),
        max_solutions=20,
        step=0.01,
        **specs,
    ):
        # run prototype constructor first
        Observatory.__init__(self, **specs)

        # populate outspec with additional inputs
        self._outspec["system"] = system
        self._outspec["preset"] = preset
        self._outspec["desired_period"] = desired_period
        self._outspec["eps"] = eps
        self._outspec["max_iter"] = max_iter
        self._outspec["max_period_days"] = max_period_days
        self._outspec["max_solutions"] = max_solutions
        self._outspec["step"] = step

        assert (
            system in _SYSTEMS
        ), f"Unknown system {system!r}; must be one of {list(_SYSTEMS)}."
        assert (
            preset in PRESETS
        ), f"Unknown preset {preset!r}; must be one of {list(PRESETS)}."
        assert system in PRESETS[preset], (
            f"Preset {preset!r} is not available for system {system!r}; "
            f"must be one of {list(PRESETS[preset])}."
        )

        if system == "SE":
            self.primary_name = "Sun"
            self.secondary_name = "Earth"
        elif system == "EM":
            self.primary_name = "Earth"
            self.secondary_name = "Moon"

        cache_string = (
            f"system={system}"
            f"|preset={preset}"
            f"|eps={eps}"
            f"|max_iter={max_iter}"
            f"|max_period_days={max_period_days}"
            f"|max_solutions={max_solutions}"
            f"|step={step}"
            f"|orbit_gen={version('orbit-gen')}"
        )

        cache_hash = hashlib.md5(cache_string.encode("utf-8")).hexdigest()
        cache_dir = Path(self.cachedir) / f"orbit_gen_{cache_hash}"

        sys = _SYSTEMS[system]
        ic = PRESETS[preset][system]

        continuation = ContinuationConfig(
            max_iter=max_iter,
            eps=eps,
            step=step,
            max_solutions=max_solutions,
            max_period_days=max_period_days,
        )

        cfg = RunConfig(
            system=sys,
            ic=ic,
            continuation=continuation,
            output_dir=cache_dir,
            show_plots=False,
            verbose=specs.get("verbose", True),
        )

        cache_path = os.path.join(cache_dir, cfg.output_filename)

        if os.path.exists(cache_path):
            # Load cached data
            with np.load(cfg.output_path) as data:
                states = data["states"]
                periods = data["periods"]
                mu_star = data["mu_star"]

            # Set up system constants using spice
            family = Family.__new__(Family)
            family.cfg = cfg
            family.orbits = []
            family._setup_constants()

            if desired_period is not None:
                idx = self.select_orbit_by_period(
                    periods, desired_period, family.cfg.system.canonical_units
                )
            else:
                idx = -1

            state = states[idx]
            period = periods[idx]

            self.observatory_orbit = Orbit(
                x0=state[0],
                z0=state[2],
                vy0=state[4],
                period=period,
                mu_star=mu_star,
                canonical_units=family.cfg.system.canonical_units,
            )

            self.observatory_orbit.propagate()

        else:
            family = Family(cfg)
            family.save()

            periods = np.array([orbit.period for orbit in family.orbits])

            if desired_period is not None:
                idx = self.select_orbit_by_period(
                    periods, desired_period, family.cfg.system.canonical_units
                )
            else:
                idx = -1

            self.observatory_orbit = family.orbits[idx]

        self.canonical_units = self.observatory_orbit.canonical_units

        self.orbit_period_days = units.time_to_dimensional(
            self.observatory_orbit.period, self.canonical_units
        )

        self.r_interp = interp1d(
            self.observatory_orbit.times,
            self.observatory_orbit.states[:, 0:3].T,
            kind="cubic",
            assume_sorted=True,
        )
        self.v_interp = interp1d(
            self.observatory_orbit.times,
            self.observatory_orbit.states[:, 3:6].T,
            kind="cubic",
            assume_sorted=True,
        )

    def select_orbit_by_period(self, periods, desired_period, canonical_units):
        """Find the generated orbit whose period is closest to the desired period.

        A warning is raised if the desired period is outside the range of the
        generated orbit periods.

        Args:
            periods (~numpy.ndarray(float)):
                Periods of the generated orbits in canonical time units.
            desired_period (float):
                Desired orbit period in days.
            canonical_units (orbit_gen.setup.system_config.CanonicalUnits):
                Canonical units of the orbit's system, used to convert the
                periods to days.

        Returns:
            int:
                Index of the orbit whose period is closest to the desired period.
        """
        periods_days = units.time_to_dimensional(periods, canonical_units).to_value(
            u.day
        )
        idx = np.argmin(np.abs(periods_days - desired_period))
        if not periods_days.min() <= desired_period <= periods_days.max():
            warnings.warn(
                f"\nDesired orbit period of {desired_period:.2f} days is outside "
                "the range of generated orbit periods "
                f"({periods_days.min():.2f} to {periods_days.max():.2f} days). "
                "Using the closest generated orbit period, "
                f"{periods_days[idx]:.2f} days. Adjust the continuation "
                "parameters if a more precise period is desired."
            )
        return idx

    def orbit(self, currentTime, eclip=False):
        """Finds observatory orbit positions vector in heliocentric equatorial
        (default) or ecliptic frame for current time (MJD).

        This method returns the telescope's position on its CR3BP orbit, as
        generated by ``orbit-gen``.

        Args:
            currentTime (~astropy.time.Time):
                Current absolute mission time in MJD. May be a single time or an
                array of n times.
            eclip (bool):
                Boolean used to switch to heliocentric ecliptic frame.
                Defaults to False, corresponding to heliocentric equatorial
                frame.

        Returns:
            ~astropy.units.Quantity(~numpy.ndarray(float)):
                Observatory orbit positions vector in AU. nx3
        """

        mjdtime = np.array(currentTime.mjd, ndmin=1)
        dt_days = mjdtime - self.orbit_epoch.to_value("mjd")
        t_canonical = units.time_to_canonical(dt_days * u.d, self.canonical_units)
        t_canonical = (
            t_canonical + self.orbit_epoch_phase * self.observatory_orbit.period
        ) % self.observatory_orbit.period

        r_synodic = self.r_interp(t_canonical).T

        r_primary = self.solarSystem_body_position(
            currentTime, self.primary_name, eclip=True
        )
        r_secondary = self.solarSystem_body_position(
            currentTime, self.secondary_name, eclip=True
        )

        sep = (r_secondary - r_primary).to_value(u.AU)

        r_synodic_secondary = r_synodic - [1 - self.observatory_orbit.mu_star, 0, 0]

        if self.secondary_name == "Earth":
            theta = np.arctan2(sep[:, 1], sep[:, 0])

            r_inertial_secondary = np.array(
                [
                    self.rot(theta[x], 3).T @ r_synodic_secondary[x, :]
                    for x in range(currentTime.size)
                ]
            )
        elif self.secondary_name == "Moon":
            h = 1 * u.hr
            sep_later = (
                self.solarSystem_body_position(
                    currentTime + h, self.secondary_name, eclip=True
                )
                - self.solarSystem_body_position(
                    currentTime + h, self.primary_name, eclip=True
                )
            ).to_value(u.AU)

            normal = np.cross(sep, sep_later)
            normal /= np.linalg.norm(normal, axis=1, keepdims=True)

            Omega = np.arctan2(normal[:, 0], -normal[:, 1])
            inc = np.arccos(normal[:, 2])
            ascending_node = np.stack(
                [np.cos(Omega), np.sin(Omega), np.zeros_like(Omega)], axis=1
            )
            arg_lat = np.arctan2(
                np.sum(sep * np.cross(normal, ascending_node), axis=1),
                np.sum(sep * ascending_node, axis=1),
            )

            r_inertial_secondary = np.array(
                [
                    self.rot(Omega[x], 3).T
                    @ self.rot(inc[x], 1).T
                    @ self.rot(arg_lat[x], 3).T
                    @ r_synodic_secondary[x, :]
                    for x in range(currentTime.size)
                ]
            )

        r_inertial_secondary_au = units.pos_to_dimensional(
            r_inertial_secondary, self.canonical_units
        ).to(u.AU)

        r_obs = r_secondary + r_inertial_secondary_au

        assert np.all(
            np.isfinite(r_obs)
        ), "Observatory positions vector r_obs has infinite value."

        if not eclip:
            r_obs = self.eclip2equat(r_obs, currentTime)

        return r_obs
